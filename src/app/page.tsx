function formatCurrency(value: number, currency = "USD") {
  return new Intl.NumberFormat("en-US", { style: "currency", currency }).format(value);
}

function labelFor(row: RecordRow, key: string, rows: RecordRow[], currency = "USD") {
  const value = row[key];
  if (key === "unit_cost" || key === "unit_price") {
    return formatCurrency(Number(value ?? 0), currency);
  }
  if (key === "is_active") return value === false ? "Inactive" : "Active";
  if (key === "contact_id") return String(rows.find((item) => item.id === value)?.name ?? "—");
  if (key === "invoice_id") {
    const invoice = rows.find((item) => item.id === value);
    return String(invoice?.invoice_number ?? value ?? "—");
  }
  if (key === "payment_date" && value) return new Date(`${String(value)}T00:00:00`).toLocaleDateString();
  if (key === "payment_method") {
    return String(value ?? "—").replaceAll("_", " ").replace(/\b\w/g, (letter) => letter.toUpperCase());
  }
  if (key === "account_id") {
    const account = rows.find((item) => item.id === value);
    return String(account?.name ?? value ?? "—");
  }
  if (key === "journal_entry_id") return String(value ?? "—").slice(0, 8);
  if (key === "total" || key === "amount") {
    const invoiceCurrency = key === "amount" && row.invoice_id
      ? rows.find((item) => item.id === row.invoice_id)?.currency
      : row.currency;
    return formatCurrency(Number(value ?? 0), String(invoiceCurrency ?? currency));
  }
  if (key === "amount_code") return value === "D" ? "Debit" : value === "C" ? "Credit" : String(value ?? "—");
  if (key === "created_at" && value) return new Date(String(value)).toLocaleDateString();
  return String(value ?? "—");
}

