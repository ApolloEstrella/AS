type AccountActivity = {
  debitCents: number;
  creditCents: number;
  hasActivity: boolean;
};

function getPostedAccountActivity(
  journalEntries: RecordRow[],
  journalLines: RecordRow[],
  fromDate?: string,
  throughDate?: string,
) {
  const entriesById = new Map(journalEntries.map((entry) => [String(entry.id), entry]));
  const activityByAccount = new Map<string, AccountActivity>();

  for (const line of journalLines) {
    const entry = entriesById.get(String(line.journal_entry_id));
    const date = String(entry?.entry_date ?? "");
    if (!entry || entry.status !== "posted" || !isValidDate(date) ||
      (fromDate && date < fromDate) || (throughDate && date > throughDate)) continue;

    const accountId = String(line.account_id);
    const amountCents = Math.round(Number(line.amount ?? 0) * 100);
    if (!Number.isFinite(amountCents) || amountCents <= 0) continue;

    const activity = activityByAccount.get(accountId) ?? {
      debitCents: 0,
      creditCents: 0,
      hasActivity: false,
    };
    if (line.amount_code === "D") activity.debitCents += amountCents;
    else if (line.amount_code === "C") activity.creditCents += amountCents;
    activity.hasActivity = true;
    activityByAccount.set(accountId, activity);
  }

  return activityByAccount;
}

type TrialBalanceRow = {
  account: RecordRow;
  debitCents: number;
  creditCents: number;
  hasActivity: boolean;
};

function TrialBalanceReport({
  title = "Trial Balance",
  accounts,
  journalEntries,
  journalLines,
  currency,
}: {
  title?: string;
  accounts: RecordRow[];
  journalEntries: RecordRow[];
  journalLines: RecordRow[];
  currency: string;
}) {
  const [asOfDate, setAsOfDate] = useState(() => {
    const now = new Date();
    return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}-${String(now.getDate()).padStart(2, "0")}`;
  });
  const dateError = !isValidDate(asOfDate);

  const reportRows = useMemo(() => {
    if (dateError) return [];
    const activityByAccount = getPostedAccountActivity(journalEntries, journalLines, undefined, asOfDate);

    return accounts
      .map((account): TrialBalanceRow => {
        const balance = activityByAccount.get(String(account.id)) ?? {
          debitCents: 0,
          creditCents: 0,
          hasActivity: false,
        };
        const netCents = balance.debitCents - balance.creditCents;
        return {
          account,
          debitCents: Math.max(netCents, 0),
          creditCents: Math.max(-netCents, 0),
          hasActivity: balance.hasActivity,
        };
      })
      .filter((row) => row.hasActivity)
      .sort((a, b) => compareAccountCodes(a.account, b.account));
  }, [accounts, asOfDate, dateError, journalEntries, journalLines]);

  const totalDebitCents = reportRows.reduce((total, row) => total + row.debitCents, 0);
  const totalCreditCents = reportRows.reduce((total, row) => total + row.creditCents, 0);
  const isBalanced = totalDebitCents === totalCreditCents;

  return (
    <>
      <div className="page-heading list-heading">
        <div>
          <p className="eyebrow">REPORTS</p>
          <h1>{title}</h1>
          <p className="muted">Ending debit and credit balances for posted accounts.</p>
        </div>
      </div>
      <div className="panel table-panel">
        <div className="ledger-filters trial-balance-filters">
          <label>
            As of
            <input
              type="date"
              value={asOfDate}
              aria-invalid={dateError}
              onChange={(event) => setAsOfDate(event.target.value)}
            />
          </label>
        </div>
        {dateError && <p className="field-error ledger-filter-error" role="alert">Choose a valid report date.</p>}
        <div className="table-toolbar">
          <div><strong>{reportRows.length} accounts</strong><span> · Posted balances through {asOfDate}</span></div>
          <strong className={`trial-balance-indicator ${isBalanced ? "balanced" : "unbalanced"}`}>
            {isBalanced ? "Debits equal credits" : "Debits do not equal credits"}
          </strong>
        </div>
        {reportRows.length === 0 ? (
          <EmptyState text={dateError ? "Enter a valid report date." : "No posted journal activity through this date."} />
        ) : (
          <div className="table-scroll">
            <table>
              <thead>
                <tr><th>Account</th><th>Type</th><th>Debit</th><th>Credit</th></tr>
              </thead>
              <tbody>
                {reportRows.map((row) => (
                  <tr key={String(row.account.id)}>
                    <td>{`${row.account.code ?? ""} ${row.account.name ?? ""}`.trim()}</td>
                    <td>{String(row.account.type ?? "—")}</td>
                    <td className="table-amount">{row.debitCents ? formatCurrency(row.debitCents / 100, currency) : "—"}</td>
                    <td className="table-amount">{row.creditCents ? formatCurrency(row.creditCents / 100, currency) : "—"}</td>
                  </tr>
                ))}
                <tr className="ledger-total">
                  <td colSpan={2}>Total</td>
                  <td className="table-amount">{formatCurrency(totalDebitCents / 100, currency)}</td>
                  <td className="table-amount">{formatCurrency(totalCreditCents / 100, currency)}</td>
                </tr>
              </tbody>
            </table>
          </div>
        )}
      </div>
    </>
  );
}

