function formatAccountBalance(balanceCents: number, currency: string) {
  if (balanceCents === 0) return formatCurrency(0, currency);
  return `${formatCurrency(Math.abs(balanceCents) / 100, currency)} ${balanceCents > 0 ? "Dr" : "Cr"}`;
}

function GeneralLedgerReport({
  accounts,
  journalEntries,
  journalLines,
  currency,
}: {
  accounts: RecordRow[];
  journalEntries: RecordRow[];
  journalLines: RecordRow[];
  currency: string;
}) {
  const [accountId, setAccountId] = useState("all");
  const [showReversals, setShowReversals] = useState(true);
  const [period, setPeriod] = useState(() => {
    const today = new Date();
    return {
      fromDate: `${today.getFullYear()}-01-01`,
      throughDate: localDateValue(today),
    };
  });
  const dateError = !isValidDate(period.fromDate) || !isValidDate(period.throughDate) ||
    period.fromDate > period.throughDate;

  const reportGroups = useMemo((): GeneralLedgerAccountGroup[] => {
    if (dateError) return [];
    const entriesById = new Map(journalEntries.map((entry) => [String(entry.id), entry]));
    const transactionsByAccount = new Map<string, GeneralLedgerTransaction[]>();

    for (const line of journalLines) {
      const entry = entriesById.get(String(line.journal_entry_id));
      const date = String(entry?.entry_date ?? "");
      const amountCents = Math.round(Number(line.amount ?? 0) * 100);
      if (!entry || entry.status !== "posted" || !isValidDate(date) || date > period.throughDate ||
        (!showReversals && Boolean(entry.reversal_of)) ||
        !Number.isFinite(amountCents) || amountCents <= 0 ||
        (line.amount_code !== "D" && line.amount_code !== "C")) continue;

      const accountKey = String(line.account_id);
      const entryDescription = String(entry.description ?? "").trim();
      const lineDescription = String(line.description ?? "").trim();
      const description = entryDescription && lineDescription && entryDescription !== lineDescription
        ? `${entryDescription} · ${lineDescription}`
        : lineDescription || entryDescription || "Journal entry";
      const transaction: GeneralLedgerTransaction = {
        id: String(line.id),
        date,
        reference: String(entry.reference ?? String(entry.id).slice(0, 8)),
        description,
        isReversal: Boolean(entry.reversal_of),
        debitCents: line.amount_code === "D" ? amountCents : 0,
        creditCents: line.amount_code === "C" ? amountCents : 0,
        order: `${String(entry.created_at ?? "")}:${String(entry.id)}:${String(line.created_at ?? "")}:${String(line.id)}`,
      };
      const transactions = transactionsByAccount.get(accountKey) ?? [];
      transactions.push(transaction);
      transactionsByAccount.set(accountKey, transactions);
    }

    return accounts
      .filter((account) => accountId === "all" || String(account.id) === accountId)
      .map((account): GeneralLedgerAccountGroup | null => {
        const transactions = (transactionsByAccount.get(String(account.id)) ?? [])
          .sort((a, b) => a.date.localeCompare(b.date) || a.order.localeCompare(b.order));
        const openingBalanceCents = transactions
          .filter((transaction) => transaction.date < period.fromDate)
          .reduce((balance, transaction) => balance + transaction.debitCents - transaction.creditCents, 0);
        let balanceCents = openingBalanceCents;
        const periodTransactions = transactions
          .filter((transaction) => transaction.date >= period.fromDate)
          .map((transaction) => {
            balanceCents += transaction.debitCents - transaction.creditCents;
            return { ...transaction, balanceCents };
          });
        if (transactions.length === 0) return null;
        return {
          account,
          openingBalanceCents,
          closingBalanceCents: balanceCents,
          debitCents: periodTransactions.reduce((total, transaction) => total + transaction.debitCents, 0),
          creditCents: periodTransactions.reduce((total, transaction) => total + transaction.creditCents, 0),
          transactions: periodTransactions,
        };
      })
      .filter((group): group is GeneralLedgerAccountGroup => group !== null)
      .sort((a, b) => compareAccountCodes(a.account, b.account));
  }, [accountId, accounts, dateError, journalEntries, journalLines, period.fromDate, period.throughDate, showReversals]);

  const transactionCount = reportGroups.reduce((total, group) => total + group.transactions.length, 0);
  const totalDebitsCents = reportGroups.reduce((total, group) => total + group.debitCents, 0);
  const totalCreditsCents = reportGroups.reduce((total, group) => total + group.creditCents, 0);

  return (
    <>
      <div className="page-heading list-heading">
        <div>
          <p className="eyebrow">REPORTS</p>
          <h1>General Ledger</h1>
          <p className="muted">Posted journal transactions grouped by account and ordered by date.</p>
          <p className="muted">Reversal entries are highlighted. Hiding them also excludes them from balances and totals.</p>
        </div>
      </div>
      <div className="panel table-panel">
        <div className="ledger-filters general-ledger-filters">
          <label>
            Account
            <select value={accountId} onChange={(event) => setAccountId(event.target.value)}>
              <option value="all">All accounts</option>
              {accounts.slice().sort(compareAccountCodes).map((account) => (
                <option key={String(account.id)} value={String(account.id)}>
                  {`${account.code ?? ""} ${account.name ?? ""}`.trim()}
                </option>
              ))}
            </select>
          </label>
          <label>
            From
            <input
              type="date"
              value={period.fromDate}
              aria-invalid={dateError}
              onChange={(event) => setPeriod((current) => ({ ...current, fromDate: event.target.value }))}
            />
          </label>
          <label>
            Through
            <input
              type="date"
              value={period.throughDate}
              aria-invalid={dateError}
              onChange={(event) => setPeriod((current) => ({ ...current, throughDate: event.target.value }))}
            />
          </label>
          <label className="ledger-reversal-toggle">
            <input type="checkbox" checked={showReversals} onChange={(event) => setShowReversals(event.target.checked)} />
            <span>Show reversal entries</span>
          </label>
        </div>
        {dateError && <p className="field-error ledger-filter-error" role="alert">Choose valid dates with the start date on or before the end date.</p>}
        <div className="table-toolbar">
          <div>
            <strong>{reportGroups.length} accounts · {transactionCount} transactions</strong>
            <span> · {period.fromDate} through {period.throughDate}</span>
          </div>
        </div>
        {reportGroups.length === 0 ? (
          <EmptyState text={dateError ? "Correct the report date range." : "No posted journal transactions in this period."} />
        ) : (
          <div className="table-scroll">
            <table>
              <thead><tr><th>Date</th><th>Reference</th><th>Description</th><th>Debit</th><th>Credit</th><th>Balance</th></tr></thead>
              <tbody>
                {reportGroups.map((group) => (
                  <Fragment key={String(group.account.id)}>
                    <tr className="statement-section-heading">
                      <th colSpan={6}>{`${group.account.code ?? ""} ${group.account.name ?? ""}`.trim()}</th>
                    </tr>
                    <tr className="subsidiary-opening">
                      <td colSpan={5}>Opening balance</td>
                      <td className="table-amount">{formatAccountBalance(group.openingBalanceCents, currency)}</td>
                    </tr>
                    {group.transactions.map((transaction) => (
                      <tr key={transaction.id} className={transaction.isReversal ? "ledger-reversal-row" : undefined}>
                        <td>{new Date(`${transaction.date}T00:00:00`).toLocaleDateString()}</td>
                        <td>{transaction.reference || "—"}</td>
                        <td>{transaction.isReversal && <span className="ledger-reversal-badge">Reversal</span>} {transaction.description}</td>
                        <td className="table-amount">{transaction.debitCents ? formatCurrency(transaction.debitCents / 100, currency) : "—"}</td>
                        <td className="table-amount">{transaction.creditCents ? formatCurrency(transaction.creditCents / 100, currency) : "—"}</td>
                        <td className="table-amount">{formatAccountBalance(transaction.balanceCents, currency)}</td>
                      </tr>
                    ))}
                    <tr className="ledger-total">
                      <td colSpan={3}>Account totals</td>
                      <td className="table-amount">{formatCurrency(group.debitCents / 100, currency)}</td>
                      <td className="table-amount">{formatCurrency(group.creditCents / 100, currency)}</td>
                      <td className="table-amount">{formatAccountBalance(group.closingBalanceCents, currency)}</td>
                    </tr>
                  </Fragment>
                ))}
                <tr className="ledger-total">
                  <td colSpan={3}>Report period totals</td>
                  <td className="table-amount">{formatCurrency(totalDebitsCents / 100, currency)}</td>
                  <td className="table-amount">{formatCurrency(totalCreditsCents / 100, currency)}</td>
                  <td></td>
                </tr>
              </tbody>
            </table>
          </div>
        )}
      </div>
    </>
  );
}

type FinancialStatementLine = {
  id: string;
  label: string;
  amountCents: number;
};

function localDateValue(date: Date) {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
}

function financialStatementLines(
  accounts: RecordRow[],
  activityByAccount: Map<string, AccountActivity>,
  type: "asset" | "liability" | "equity" | "revenue" | "expense",
): FinancialStatementLine[] {
  return accounts
    .filter((account) => account.type === type)
    .map((account) => {
      const activity = activityByAccount.get(String(account.id));
      const amountCents = !activity
        ? 0
        : type === "asset" || type === "expense"
          ? activity.debitCents - activity.creditCents
          : activity.creditCents - activity.debitCents;
      return {
        id: String(account.id),
        label: `${account.code ?? ""} ${account.name ?? ""}`.trim(),
        amountCents,
        hasActivity: Boolean(activity?.hasActivity),
      };
    })
    .filter((line) => line.hasActivity)
    .sort((a, b) => a.label.localeCompare(b.label, undefined, { numeric: true, sensitivity: "base" }));
}

function BalanceSheetReport({
  accounts,
  journalEntries,
  journalLines,
  currency,
}: {
  accounts: RecordRow[];
  journalEntries: RecordRow[];
  journalLines: RecordRow[];
  currency: string;
}) {
  const [asOfDate, setAsOfDate] = useState(() => localDateValue(new Date()));
  const dateError = !isValidDate(asOfDate);

  const report = useMemo(() => {
    if (dateError) {
      return { assets: [], liabilities: [], equity: [], netIncomeCents: 0, hasActivity: false };
    }

    const activityByAccount = getPostedAccountActivity(journalEntries, journalLines, undefined, asOfDate);
    const assets = financialStatementLines(accounts, activityByAccount, "asset");
    const liabilities = financialStatementLines(accounts, activityByAccount, "liability");
    const equity = financialStatementLines(accounts, activityByAccount, "equity");
    const revenue = financialStatementLines(accounts, activityByAccount, "revenue");
    const expenses = financialStatementLines(accounts, activityByAccount, "expense");
    const netIncomeCents =
      revenue.reduce((total, line) => total + line.amountCents, 0) -
      expenses.reduce((total, line) => total + line.amountCents, 0);

    return {
      assets,
      liabilities,
      equity,
      netIncomeCents,
      hasActivity: assets.length + liabilities.length + equity.length + revenue.length + expenses.length > 0,
    };
  }, [accounts, asOfDate, dateError, journalEntries, journalLines]);

  const totalAssetsCents = report.assets.reduce((total, line) => total + line.amountCents, 0);
  const totalLiabilitiesCents = report.liabilities.reduce((total, line) => total + line.amountCents, 0);
  const totalEquityCents = report.equity.reduce((total, line) => total + line.amountCents, 0) + report.netIncomeCents;
  const isBalanced = totalAssetsCents === totalLiabilitiesCents + totalEquityCents;
  const hasActivity = report.hasActivity;
  const renderLines = (lines: FinancialStatementLine[]) => lines.map((line) => (
    <tr key={line.id}>
      <td>{line.label}</td>
      <td className="table-amount">{formatCurrency(line.amountCents / 100, currency)}</td>
    </tr>
  ));

  return (
    <>
      <div className="page-heading list-heading">
        <div>
          <p className="eyebrow">REPORTS</p>
          <h1>Balance Sheet</h1>
          <p className="muted">Assets, liabilities, and equity from posted entries through the selected date.</p>
        </div>
      </div>
      <div className="panel table-panel">
        <div className="ledger-filters trial-balance-filters">
          <label>
            As of
            <input type="date" value={asOfDate} aria-invalid={dateError} onChange={(event) => setAsOfDate(event.target.value)} />
          </label>
        </div>
        {dateError && <p className="field-error ledger-filter-error" role="alert">Choose a valid report date.</p>}
        <div className="table-toolbar">
          <div><strong>As of {asOfDate}</strong><span> · Includes unclosed net income</span></div>
          {hasActivity && (
            <strong className={`trial-balance-indicator ${isBalanced ? "balanced" : "unbalanced"}`}>
              {isBalanced ? "Assets equal liabilities and equity" : "Balance sheet is out of balance"}
            </strong>
          )}
        </div>
        {!hasActivity ? (
          <EmptyState text={dateError ? "Enter a valid report date." : "No posted balance sheet activity through this date."} />
        ) : (
          <div className="table-scroll">
            <table>
              <thead><tr><th>Account</th><th>Balance</th></tr></thead>
              <tbody>
                <tr className="statement-section-heading"><th colSpan={2}>Assets</th></tr>
                {renderLines(report.assets)}
                <tr className="ledger-total"><td>Total assets</td><td>{formatCurrency(totalAssetsCents / 100, currency)}</td></tr>
                <tr className="statement-section-heading"><th colSpan={2}>Liabilities</th></tr>
                {renderLines(report.liabilities)}
                <tr className="ledger-total"><td>Total liabilities</td><td>{formatCurrency(totalLiabilitiesCents / 100, currency)}</td></tr>
                <tr className="statement-section-heading"><th colSpan={2}>Equity</th></tr>
                {renderLines(report.equity)}
                <tr><td>Unclosed net income</td><td className="table-amount">{formatCurrency(report.netIncomeCents / 100, currency)}</td></tr>
                <tr className="ledger-total"><td>Total equity</td><td>{formatCurrency(totalEquityCents / 100, currency)}</td></tr>
                <tr className="ledger-total"><td>Total liabilities and equity</td><td>{formatCurrency((totalLiabilitiesCents + totalEquityCents) / 100, currency)}</td></tr>
              </tbody>
            </table>
          </div>
        )}
      </div>
    </>
  );
}

