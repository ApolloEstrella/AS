function isValidDate(value: string) {
  const parsed = new Date(`${value}T00:00:00.000Z`);
  return /^\d{4}-\d{2}-\d{2}$/.test(value) && !Number.isNaN(parsed.getTime()) &&
    parsed.toISOString().slice(0, 10) === value;
}

function isValidEmail(value: string) {
  return value.length <= 254 && /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value);
}

function validateRecord(
  area: Area,
  values: Record<string, string>,
  rows: Record<string, RecordRow[]>,
  editingId?: string,
) {
  const errors: Record<string, string> = {};
  const fields = forms[area] ?? [];

  for (const field of fields) {
    const value = values[field.name] ?? "";
    if (field.required && !value) {
      errors[field.name] = `${field.label} is required.`;
      continue;
    }
    if (!value) continue;

    if (field.maxLength !== undefined && value.length > field.maxLength) {
      errors[field.name] = `${field.label} must be ${field.maxLength} characters or fewer.`;
    } else if (field.options && !field.options.includes(value)) {
      errors[field.name] = `Choose a valid ${field.label.toLowerCase()}.`;
    } else if (field.type === "date" && !isValidDate(value)) {
      errors[field.name] = `Enter a valid ${field.label.toLowerCase()}.`;
    } else if (field.type === "number") {
      const number = Number(value);
      const decimalPart = value.split(".")[1] ?? "";
      if (!Number.isFinite(number)) {
        errors[field.name] = `${field.label} must be a valid number.`;
      } else if (field.min !== undefined && number < field.min) {
        errors[field.name] = `${field.label} must be at least ${field.min}.`;
      } else if (field.max !== undefined && number > field.max) {
        errors[field.name] = `${field.label} must be no more than ${field.max}.`;
      } else if (field.decimalPlaces !== undefined && decimalPart.length > field.decimalPlaces) {
        errors[field.name] = `${field.label} can have at most ${field.decimalPlaces} decimal places.`;
      }
    } else if (field.type === "email" && !isValidEmail(value)) {
      errors[field.name] = "Enter a valid email address.";
    } else if (field.name === "phone" &&
      (!/^[+()\d.\-\sxX#]+$/.test(value) || (value.match(/\d/g) ?? []).length < 7 || (value.match(/\d/g) ?? []).length > 20)) {
      errors[field.name] = "Enter a phone number with 7 to 20 digits.";
    } else if (field.name === "currency" && !/^[A-Z]{3}$/.test(value)) {
      errors[field.name] = "Enter a three-letter uppercase currency code.";
    } else if (field.name === "code" && !/^[A-Za-z0-9][A-Za-z0-9._/-]*$/.test(value)) {
      errors[field.name] = "Use letters, numbers, periods, hyphens, underscores, or slashes in the account code.";
    }

    if (errors[field.name]) continue;

    if (field.type === "account" || field.type === "expense-account" || field.type === "cash-account" ||
      field.type === "contact" || field.type === "journal-entry" || field.type === "payment-invoice") {
      const resource = field.type === "account" || field.type === "expense-account" || field.type === "cash-account"
        ? "accounts"
        : field.type === "contact" ? "contacts"
          : field.type === "payment-invoice" ? "invoices" : "journal-entries";
      const relatedRecord = (rows[resource] ?? []).find((row) => String(row.id) === value);
      if (!relatedRecord ||
        (field.type === "expense-account" && (relatedRecord.type !== "expense" || relatedRecord.is_active === false)) ||
        (field.type === "cash-account" && (relatedRecord.type !== "asset" || relatedRecord.is_active === false || !String(relatedRecord.code ?? "").startsWith("10"))) ||
        (field.type === "contact" && area === "invoices" && relatedRecord.type !== "customer" && relatedRecord.type !== "both") ||
        (field.type === "payment-invoice" && ["draft", "void"].includes(String(relatedRecord.status))) ||
        (field.type === "journal-entry" && ["posted", "void"].includes(String(relatedRecord.status)))) {
        errors[field.name] = `Choose an available ${field.label.toLowerCase()}.`;
      }
    }
  }

  if (area === "invoices") {
    const invoiceNumber = values.invoice_number ?? "";
    if (invoiceNumber && (rows.invoices ?? []).some((row) =>
      String(row.id) !== editingId && String(row.invoice_number ?? "") === invoiceNumber)) {
      errors.invoice_number = "This invoice number is already in use.";
    }
    const issueDate = values.issue_date ?? "";
    const dueDate = values.due_date ?? "";
    if (isValidDate(issueDate) && isValidDate(dueDate) && dueDate < issueDate) {
      errors.due_date = "Due date cannot be earlier than the issue date.";
    }
  }

  if (area === "invoice-payments") {
    const invoice = (rows.invoices ?? []).find((row) => String(row.id) === values.invoice_id);
    const amount = Number(values.amount);
    if (invoice && Number.isFinite(amount) && amount > 0) {
      const alreadyPaidCents = (rows["invoice-payments"] ?? [])
        .filter((payment) => String(payment.id) !== editingId && String(payment.invoice_id) === values.invoice_id)
        .reduce((total, payment) => total + Math.round(Number(payment.amount ?? 0) * 100), 0);
      const invoiceTotalCents = Math.round(Number(invoice.total ?? 0) * 100);
      if (alreadyPaidCents + Math.round(amount * 100) > invoiceTotalCents) {
        errors.amount = "Payment cannot exceed the remaining invoice balance.";
      }
    }
  }

  if (area === "accounts") {
    const code = values.code ?? "";
    if (code && (rows.accounts ?? []).some((row) =>
      String(row.id) !== editingId && String(row.code ?? "") === code)) {
      errors.code = "This account code is already in use.";
    }
  }

  if (area === "inventory") {
    const sku = values.sku ?? "";
    if (sku && !/^[A-Za-z0-9][A-Za-z0-9._/-]*$/.test(sku)) {
      errors.sku = "Start with a letter or number; use only letters, numbers, periods, hyphens, underscores, or slashes.";
    } else if (sku && (rows.inventory ?? []).some((row) =>
      String(row.id) !== editingId && String(row.sku ?? "").toLowerCase() === sku.toLowerCase())) {
      errors.sku = "This SKU is already in use.";
    }
  }

  return errors;
}

