  async function submitRecord(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (!activeResource) return;
    setError("");
    const formData = new FormData(event.currentTarget);
    const values: Record<string, string> = {};
    for (const field of fieldConfig) {
      values[field.name] = String(formData.get(field.name) ?? "").trim();
    }
    if (area === "invoices") {
      values.currency = (values.currency || String(organization?.currency ?? "USD")).toUpperCase();
      values.total = (invoiceTotalCents / 100).toFixed(2);
      if (invoiceAlreadyPaid && !editing) values.status = "sent";
    }
    if (area === "expenses") {
      values.status = expenseStatus || "unpaid";
      values.payment_account_id = expenseStatus === "paid" ? expensePaymentAccountId : "";
    }
    if (area === "journal-entries") values.status = values.status || "draft";

    const nextErrors = validateRecord(area, values, rows, editing ? String(editing.id) : undefined);
    if (area === "expenses" && values.status === "paid" &&
      !(rows.accounts ?? []).some((account) =>
        String(account.id) === expensePaymentAccountId &&
        account.type === "asset" &&
        account.is_active !== false &&
        String(account.code ?? "").startsWith("10"))) {
      nextErrors.payment_account_id = "Choose an active cash or bank payment account.";
    }
    if (area === "invoices") {
      if (invoiceLines.length === 0) nextErrors.invoice_lines = "Add at least one invoice line.";
      if (!invoiceTaxExempt) {
        const rate = Number(invoiceTaxRate);
        if (!/^\d+(\.\d{1,2})?$/.test(invoiceTaxRate) || !Number.isFinite(rate) || rate < 0 || rate > 100) {
          nextErrors.tax_rate = "Enter a tax rate from 0 to 100 with at most 2 decimal places.";
        }
      }
      if (values.status === "paid" && !invoiceAlreadyPaid && editing?.status !== "paid") {
        const paymentsReceivedCents = editing
          ? (rows["invoice-payments"] ?? [])
            .filter((payment) => String(payment.invoice_id) === String(editing.id))
            .reduce((total, payment) => total + Math.round(Number(payment.amount ?? 0) * 100), 0)
          : 0;
        if (!editing || paymentsReceivedCents < invoiceTotalCents) {
          nextErrors.status = "Record payments covering the invoice total before marking it paid.";
        }
      }
      if (editing?.status === "paid" && values.status !== "paid" && invoiceTotalCents > 0) {
        const paymentsReceivedCents = (rows["invoice-payments"] ?? [])
          .filter((payment) => String(payment.invoice_id) === String(editing.id))
          .reduce((total, payment) => total + Math.round(Number(payment.amount ?? 0) * 100), 0);
        if (paymentsReceivedCents >= invoiceTotalCents) {
          nextErrors.status = "This invoice is fully paid. Delete or reduce its recorded payments first; payment changes update the invoice status and reverse the ledger entry.";
        }
      }
      if (invoiceAlreadyPaid && !editing) {
        if (invoiceTotalCents <= 0) {
          nextErrors.already_paid = "A zero-total invoice cannot have a payment recorded.";
        }
        if (!isValidDate(invoicePaymentDate)) {
          nextErrors.invoice_payment_date = "Enter a valid payment date.";
        }
        if (!(rows.accounts ?? []).some((account) =>
          String(account.id) === invoicePaymentAccountId &&
          account.type === "asset" &&
          account.is_active !== false &&
          String(account.code ?? "").startsWith("10"))) {
          nextErrors.invoice_payment_account = "Choose an active cash or bank deposit account.";
        }
        if (!["cash", "check", "card", "bank_transfer", "other"].includes(invoicePaymentMethod)) {
          nextErrors.invoice_payment_method = "Choose a valid payment method.";
        }
        if (invoicePaymentReference.trim().length > 100) {
          nextErrors.invoice_payment_reference = "Reference must be 100 characters or fewer.";
        }
      }
      for (const line of invoiceLines) {
        const prefix = `invoice-line-${line.key}`;
        if (!line.description.trim()) nextErrors[`${prefix}-description`] = "Description is required.";
        else if (line.description.trim().length > 500) {
          nextErrors[`${prefix}-description`] = "Description must be 500 characters or fewer.";
        }
        const quantity = Number(line.quantity);
        const quantityDecimals = line.quantity.split(".")[1] ?? "";
        if (!line.quantity || !Number.isFinite(quantity) || quantity <= 0 ||
          quantity > 999999999.999 || quantityDecimals.length > 3) {
          nextErrors[`${prefix}-quantity`] = "Quantity must be greater than zero with at most 3 decimal places.";
        }
        const unitPrice = Number(line.unit_price);
        const priceDecimals = line.unit_price.split(".")[1] ?? "";
        if (!line.unit_price || !Number.isFinite(unitPrice) || unitPrice < 0 ||
          unitPrice > 999999999999.99 || priceDecimals.length > 2) {
          nextErrors[`${prefix}-unit_price`] = "Unit price must be zero or more with at most 2 decimal places.";
        }
        if (line.inventory_id && !(rows.inventory ?? []).some((item) =>
          String(item.id) === line.inventory_id && item.is_active !== false)) {
          nextErrors[`${prefix}-inventory_id`] = "Choose an active inventory item.";
        }
        if (line.account_id && !(rows.accounts ?? []).some((account) =>
          String(account.id) === line.account_id && account.type === "revenue" && account.is_active !== false)) {
          nextErrors[`${prefix}-account_id`] = "Choose an active revenue account.";
        }
      }
    }
    if (area === "journal-entries") {
      if (journalLineDrafts.length < 2) {
        nextErrors.journal_lines = "Add at least two journal lines.";
      }
      let debitCents = 0;
      let creditCents = 0;
      for (const line of journalLineDrafts) {
        const prefix = `journal-line-${line.key}`;
        if (!line.account_id) {
          nextErrors[`${prefix}-account_id`] = "Choose an account.";
        } else if (!(rows.accounts ?? []).some((account) =>
          String(account.id) === line.account_id && account.is_active !== false)) {
          nextErrors[`${prefix}-account_id`] = "Choose an active account.";
        }

        const debit = line.debit.trim();
        const credit = line.credit.trim();
        if (Boolean(debit) === Boolean(credit)) {
          nextErrors[`${prefix}-amount`] = debit
            ? "Enter either a debit or a credit, not both."
            : "Enter a debit or a credit amount.";
        } else {
          const value = debit || credit;
          const amount = Number(value);
          if (!/^\d+(\.\d{1,2})?$/.test(value) || !Number.isFinite(amount) ||
            amount <= 0 || amount > 999999999999.99) {
            nextErrors[`${prefix}-amount`] = "Enter a positive amount with at most 2 decimal places.";
          } else if (debit) debitCents += amountToCents(debit);
          else creditCents += amountToCents(credit);
        }

        if (line.description.trim().length > 500) {
          nextErrors[`${prefix}-description`] = "Description must be 500 characters or fewer.";
        }
      }
      if (debitCents <= 0 || debitCents !== creditCents) {
        nextErrors.journal_balance = "Total debits and credits must be equal and greater than zero.";
      }
    }
    setValidationErrors(nextErrors);
    if (Object.keys(nextErrors).length > 0) return;

    setBusy(true);
    const body: Record<string, unknown> = {};
    for (const field of fieldConfig) {
      const value = values[field.name];
      if (value !== "") {
        body[field.name] = field.type === "number"
          ? Number(value)
          : area === "inventory" && field.name === "is_active"
            ? value === "true"
            : value;
      } else if (area === "inventory" && field.name === "description") {
        body.description = null;
      } else if (area === "invoice-payments" && (field.name === "reference" || field.name === "notes")) {
        body[field.name] = null;
      }
    }
    if (area === "invoices") {
      body.is_tax_exempt = invoiceTaxExempt;
      body.tax_rate = invoiceTaxExempt ? 0 : Number(invoiceTaxRate);
      body.tax_amount = invoiceTaxCents / 100;
    }
    if (area === "expenses") {
      body.payment_account_id = values.status === "paid" ? expensePaymentAccountId : null;
    }
    try {
      if (area === "journal-entries") {
        await request("journal-entries/save", "POST", {
          organization_id: organization?.id,
          entry_id: editing?.id ?? null,
          entry: body,
          lines: journalLineDrafts.map((line) => ({
            account_id: line.account_id,
            amount: Number(line.debit || line.credit),
            amount_code: line.debit ? "D" : "C",
            description: line.description.trim() || null,
          })),
        });
        await refreshData();
        closeRecordForm();
        return;
      }
      if (area === "invoices" && invoiceAlreadyPaid && !editing) {
        await request("invoices/paid", "POST", {
          organization_id: organization?.id,
          invoice: body,
          items: invoiceLines.map((line) => ({
            inventory_id: line.inventory_id || null,
            description: line.description.trim(),
            quantity: Number(line.quantity),
            unit_price: Number(line.unit_price),
            account_id: line.account_id || null,
          })),
          payment: {
            payment_date: invoicePaymentDate,
            account_id: invoicePaymentAccountId,
            payment_method: invoicePaymentMethod,
            reference: invoicePaymentReference.trim() || null,
          },
        });
        await refreshData();
        closeRecordForm();
        return;
      }
      if (area === "invoices") {
        const invoice = editing
          ? await request(activeResource, "PATCH", body, String(editing.id)) as RecordRow
          : await request(activeResource, "POST", { ...body, organization_id: organization?.id }) as RecordRow;
        if (!editing) {
          setEditing(invoice);
          setInvoiceItemsLoadedFor(String(invoice.id));
        }
        for (const id of deletedInvoiceLineIds) {
          await request("invoice-items", "DELETE", undefined, id);
          setDeletedInvoiceLineIds((current) => current.filter((deletedId) => deletedId !== id));
        }
        for (const line of invoiceLines) {
          const itemBody = {
            inventory_id: line.inventory_id || null,
            description: line.description.trim(),
            quantity: Number(line.quantity),
            unit_price: Number(line.unit_price),
            account_id: line.account_id || null,
          };
          if (line.id) {
            await request("invoice-items", "PATCH", itemBody, line.id);
          } else {
            const created = await request("invoice-items", "POST", {
              ...itemBody,
              invoice_id: invoice.id,
              organization_id: organization?.id,
            }) as RecordRow;
            setInvoiceLines((current) => current.map((item) =>
              item.key === line.key ? { ...item, id: String(created.id) } : item,
            ));
          }
        }
      } else if (editing) await request(activeResource, "PATCH", body, String(editing.id));
      else await request(activeResource, "POST", { ...body, organization_id: organization?.id });
      await refreshData();
      closeRecordForm();
    } catch (reason) {
      setError(String(reason instanceof Error ? reason.message : reason));
    } finally {
      setBusy(false);
    }
  }

