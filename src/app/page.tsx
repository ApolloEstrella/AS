type CustomerLedgerTransaction = {
  id: string;
  contactId: string;
  date: string;
  transaction: string;
  reference: string;
  debitCents: number;
  creditCents: number;
};

type CustomerLedgerGroup = {
  contact: RecordRow;
  openingBalanceCents: number;
  closingBalanceCents: number;
  transactions: Array<CustomerLedgerTransaction & { balanceCents: number }>;
};

type VendorLedgerExpense = {
  id: string;
  date: string;
  description: string;
  reference: string;
  amountCents: number;
  status: string;
};

type VendorLedgerGroup = {
  contact: RecordRow;
  expenses: VendorLedgerExpense[];
  openingTotalCents: number;
  openingPaidCents: number;
  openingDueCents: number;
  totalCents: number;
  paidCents: number;
  dueCents: number;
  closingDueCents: number;
};

function SubsidiaryLedgerReport({
  kind,
  contacts,
  invoices,
  invoicePayments,
  expenses,
  currency,
}: {
  kind: "customer" | "vendor";
  contacts: RecordRow[];
  invoices: RecordRow[];
  invoicePayments: RecordRow[];
  expenses: RecordRow[];
  currency: string;
}) {
  const [contactId, setContactId] = useState("all");
  const [period, setPeriod] = useState(() => {
    const today = new Date();
    return {
      fromDate: `${today.getFullYear()}-01-01`,
      throughDate: localDateValue(today),
    };
  });
  const dateError = !isValidDate(period.fromDate) || !isValidDate(period.throughDate) ||
    period.fromDate > period.throughDate;
  const entityLabel = kind === "customer" ? "customer" : "vendor";
  const contactOptions = useMemo(() => {
    const expenseContactIds = new Set(expenses
      .filter((expense) => expense.status !== "void" && expense.contact_id)
      .map((expense) => String(expense.contact_id)));
    const options = contacts.filter((contact) => kind === "customer"
      ? contact.type === "customer" || contact.type === "both"
      : contact.type === "vendor" || contact.type === "both" || expenseContactIds.has(String(contact.id)));
    if (kind === "vendor" && expenses.some((expense) => expense.status !== "void" && !expense.contact_id)) {
      options.push({ id: "__unassigned_vendor__", name: "Unassigned vendor", type: "vendor" });
    }
    return options.sort((a, b) =>
      String(a.name ?? "").localeCompare(String(b.name ?? ""), undefined, { sensitivity: "base" }));
  }, [contacts, expenses, kind]);

  const customerGroups = useMemo((): CustomerLedgerGroup[] => {
    if (kind !== "customer" || dateError) return [];
    const availableContacts = contactOptions.filter((contact) => contactId === "all" || String(contact.id) === contactId);
    const contactIds = new Set(availableContacts.map((contact) => String(contact.id)));
    const invoiceById = new Map(invoices.map((invoice) => [String(invoice.id), invoice]));
    const transactionRows: CustomerLedgerTransaction[] = [];

    for (const invoice of invoices) {
      const date = String(invoice.issue_date ?? "");
      if (!contactIds.has(String(invoice.contact_id)) ||
        !["sent", "paid", "overdue"].includes(String(invoice.status)) ||
        !isValidDate(date) || date > period.throughDate) continue;
      transactionRows.push({
        id: `invoice-${invoice.id}`,
        contactId: String(invoice.contact_id),
        date,
        transaction: "Invoice",
        reference: String(invoice.invoice_number ?? ""),
        debitCents: Math.round(Number(invoice.total ?? 0) * 100),
        creditCents: 0,
      });
    }

    for (const payment of invoicePayments) {
      const invoice = invoiceById.get(String(payment.invoice_id));
      const date = String(payment.payment_date ?? "");
      if (!invoice || !contactIds.has(String(invoice.contact_id)) ||
        !["sent", "paid", "overdue"].includes(String(invoice.status)) ||
        !isValidDate(date) || date > period.throughDate) continue;
      transactionRows.push({
        id: `payment-${payment.id}`,
        contactId: String(invoice.contact_id),
        date,
        transaction: `Payment${payment.payment_method ? ` (${String(payment.payment_method).replaceAll("_", " ")})` : ""}`,
        reference: String(payment.reference || invoice.invoice_number || ""),
        debitCents: 0,
        creditCents: Math.round(Number(payment.amount ?? 0) * 100),
      });
    }

    return availableContacts.flatMap((contact) => {
      const rows = transactionRows
        .filter((transaction) => transaction.contactId === String(contact.id))
        .sort((a, b) => a.date.localeCompare(b.date) ||
          Number(b.debitCents > 0) - Number(a.debitCents > 0) ||
          a.reference.localeCompare(b.reference, undefined, { numeric: true, sensitivity: "base" }));
      const openingBalanceCents = rows
        .filter((transaction) => transaction.date < period.fromDate)
        .reduce((balance, transaction) => balance + transaction.debitCents - transaction.creditCents, 0);
      let balanceCents = openingBalanceCents;
      const periodTransactions = rows
        .filter((transaction) => transaction.date >= period.fromDate)
        .map((transaction) => {
          balanceCents += transaction.debitCents - transaction.creditCents;
          return { ...transaction, balanceCents };
        });
      if (openingBalanceCents === 0 && periodTransactions.length === 0) return [];
      return [{
        contact,
        openingBalanceCents,
        closingBalanceCents: balanceCents,
        transactions: periodTransactions,
      }];
    });
  }, [contactId, contactOptions, dateError, invoices, invoicePayments, kind, period.fromDate, period.throughDate]);

  const vendorGroups = useMemo((): VendorLedgerGroup[] => {
    if (kind !== "vendor" || dateError) return [];
    const availableContacts = contactOptions.filter((contact) => contactId === "all" || String(contact.id) === contactId);

    return availableContacts.flatMap((contact) => {
      const isUnassignedVendor = String(contact.id) === "__unassigned_vendor__";
      const allExpenses = expenses.filter((expense) => {
        const expenseDate = String(expense.expense_date ?? "");
        const matchesContact = isUnassignedVendor
          ? !expense.contact_id
          : String(expense.contact_id ?? "") === String(contact.id);
        return matchesContact && expense.status !== "void" && isValidDate(expenseDate) &&
          expenseDate <= period.throughDate;
      });
      const toLedgerExpense = (expense: RecordRow): VendorLedgerExpense => ({
          id: String(expense.id),
          date: String(expense.expense_date),
          description: String(expense.description ?? ""),
          reference: String(expense.id ?? "").slice(0, 8),
          amountCents: Math.round(Number(expense.amount ?? 0) * 100),
          status: String(expense.status ?? "unpaid"),
        });
      const openingExpenses = allExpenses.filter((expense) => String(expense.expense_date) < period.fromDate);
      const vendorExpenses = allExpenses
        .filter((expense) => String(expense.expense_date) >= period.fromDate)
        .map(toLedgerExpense)
        .sort((a, b) => a.date.localeCompare(b.date) || a.reference.localeCompare(b.reference));
      if (allExpenses.length === 0) return [];
      const openingTotalCents = openingExpenses
        .reduce((total, expense) => total + Math.round(Number(expense.amount ?? 0) * 100), 0);
      const openingPaidCents = openingExpenses
        .filter((expense) => expense.status === "paid")
        .reduce((total, expense) => total + Math.round(Number(expense.amount ?? 0) * 100), 0);
      const openingDueCents = openingTotalCents - openingPaidCents;
      const totalCents = vendorExpenses.reduce((total, expense) => total + expense.amountCents, 0);
      const paidCents = vendorExpenses
        .filter((expense) => expense.status === "paid")
        .reduce((total, expense) => total + expense.amountCents, 0);
      return [{
        contact,
        expenses: vendorExpenses,
        openingTotalCents,
        openingPaidCents,
        openingDueCents,
        totalCents,
        paidCents,
        dueCents: totalCents - paidCents,
        closingDueCents: openingDueCents + totalCents - paidCents,
      }];
    });
  }, [contactId, contactOptions, dateError, expenses, kind, period.fromDate, period.throughDate]);

  const totalCustomerBalanceCents = customerGroups.reduce((total, group) => total + group.closingBalanceCents, 0);
  const totalVendorExpensesCents = vendorGroups.reduce((total, group) => total + group.totalCents, 0);
  const totalVendorPaidCents = vendorGroups.reduce((total, group) => total + group.paidCents, 0);
  const totalVendorDueCents = vendorGroups.reduce((total, group) => total + group.closingDueCents, 0);
  const hasRows = kind === "customer" ? customerGroups.length > 0 : vendorGroups.length > 0;

  return (
    <>
      <div className="page-heading list-heading">
        <div>
          <p className="eyebrow">SUBSIDIARY LEDGERS</p>
          <h1>{kind === "customer" ? "Customer Subsidiary Ledger" : "Vendor Subsidiary Ledger"}</h1>
          <p className="muted">
            {kind === "customer"
              ? "Invoice charges and recorded payments by customer, with running receivable balances."
              : "Vendor expenses by date and current paid status. Unassigned expenses are grouped separately; vendor payments are not recorded separately."}
          </p>
        </div>
      </div>
      <div className="panel table-panel">
        <div className="ledger-filters subsidiary-filters">
          <label>
            {kind === "customer" ? "Customer" : "Vendor"}
            <select value={contactId} onChange={(event) => setContactId(event.target.value)}>
              <option value="all">All {kind === "customer" ? "customers" : "vendors"}</option>
              {contactOptions.map((contact) => (
                <option key={String(contact.id)} value={String(contact.id)}>{String(contact.name ?? "Unnamed")}</option>
              ))}
            </select>
          </label>
          <label>
            From
            <input
              type="date"
              value={period.fromDate}
              aria-invalid={dateError}
              onChange={(event) => setPeriod((current) => ({ ...current, fromDate: event.target.value }))}
            />
          </label>
          <label>
            Through
            <input
              type="date"
              value={period.throughDate}
              aria-invalid={dateError}
              onChange={(event) => setPeriod((current) => ({ ...current, throughDate: event.target.value }))}
            />
          </label>
        </div>
        {dateError && <p className="field-error ledger-filter-error" role="alert">Choose valid dates with the start date on or before the end date.</p>}
        <div className="table-toolbar">
          <div><strong>{period.fromDate}</strong><span> through {period.throughDate}</span></div>
          {kind === "customer" ? (
            <strong>Ending receivables: {formatCurrency(totalCustomerBalanceCents / 100, currency)}</strong>
          ) : (
            <strong>Period expenses: {formatCurrency(totalVendorExpensesCents / 100, currency)} · Ending due: {formatCurrency(totalVendorDueCents / 100, currency)}</strong>
          )}
        </div>
        {!hasRows ? (
          <EmptyState text={dateError
            ? "Correct the report date range."
            : contactOptions.length === 0
              ? `No ${entityLabel} contacts are available.`
              : `No ${entityLabel} ledger activity in this period.`} />
        ) : kind === "customer" ? (
          <div className="table-scroll">
            <table>
              <thead><tr><th>Date</th><th>Transaction</th><th>Reference</th><th>Debit</th><th>Credit</th><th>Balance</th></tr></thead>
              <tbody>
                {customerGroups.map((group) => (
                  <Fragment key={String(group.contact.id)}>
                    <tr className="statement-section-heading">
                      <th colSpan={6}>{String(group.contact.name ?? "Customer")} · Closing balance {formatCurrency(group.closingBalanceCents / 100, currency)}</th>
                    </tr>
                    <tr className="subsidiary-opening">
                      <td colSpan={5}>Opening balance</td>
                      <td className="table-amount">{formatCurrency(group.openingBalanceCents / 100, currency)}</td>
                    </tr>
                    {group.transactions.map((transaction) => (
                      <tr key={transaction.id}>
                        <td>{new Date(`${transaction.date}T00:00:00`).toLocaleDateString()}</td>
                        <td>{transaction.transaction}</td>
                        <td>{transaction.reference || "—"}</td>
                        <td className="table-amount">{transaction.debitCents ? formatCurrency(transaction.debitCents / 100, currency) : "—"}</td>
                        <td className="table-amount">{transaction.creditCents ? formatCurrency(transaction.creditCents / 100, currency) : "—"}</td>
                        <td className="table-amount">{formatCurrency(transaction.balanceCents / 100, currency)}</td>
                      </tr>
                    ))}
                    <tr className="ledger-total">
                      <td colSpan={5}>Closing balance</td>
                      <td className="table-amount">{formatCurrency(group.closingBalanceCents / 100, currency)}</td>
                    </tr>
                  </Fragment>
                ))}
                <tr className="ledger-total">
                  <td colSpan={5}>All customers</td>
                  <td className="table-amount">{formatCurrency(totalCustomerBalanceCents / 100, currency)}</td>
                </tr>
              </tbody>
            </table>
          </div>
        ) : (
          <div className="table-scroll">
            <table>
              <thead><tr><th>Date</th><th>Expense</th><th>Reference</th><th>Amount</th><th>Status</th></tr></thead>
              <tbody>
                {vendorGroups.map((group) => (
                  <Fragment key={String(group.contact.id)}>
                    <tr className="statement-section-heading">
                      <th colSpan={5}>{String(group.contact.name ?? "Vendor")} · Ending due {formatCurrency(group.closingDueCents / 100, currency)}</th>
                    </tr>
                    {group.openingTotalCents > 0 && (
                      <tr className="subsidiary-opening">
                        <td colSpan={3}>Opening expenses · marked paid · due</td>
                        <td className="table-amount">
                          {formatCurrency(group.openingTotalCents / 100, currency)} · {formatCurrency(group.openingPaidCents / 100, currency)} · {formatCurrency(group.openingDueCents / 100, currency)}
                        </td>
                        <td></td>
                      </tr>
                    )}
                    {group.expenses.map((expense) => (
                      <tr key={expense.id}>
                        <td>{new Date(`${expense.date}T00:00:00`).toLocaleDateString()}</td>
                        <td>{expense.description || "Expense"}</td>
                        <td>{expense.reference}</td>
                        <td className="table-amount">{formatCurrency(expense.amountCents / 100, currency)}</td>
                        <td><span className={`status-pill status-${expense.status}`}>{expense.status}</span></td>
                      </tr>
                    ))}
                    <tr className="ledger-total">
                      <td colSpan={3}>Period expenses</td>
                      <td className="table-amount">{formatCurrency(group.totalCents / 100, currency)}</td>
                      <td></td>
                    </tr>
                    <tr className="subsidiary-opening">
                      <td colSpan={3}>Period paid · Ending due</td>
                      <td className="table-amount">{formatCurrency(group.paidCents / 100, currency)} · {formatCurrency(group.closingDueCents / 100, currency)}</td>
                      <td></td>
                    </tr>
                  </Fragment>
                ))}
                <tr className="ledger-total">
                  <td colSpan={3}>All vendors · period paid · ending due</td>
                  <td className="table-amount">{formatCurrency(totalVendorExpensesCents / 100, currency)} · {formatCurrency(totalVendorPaidCents / 100, currency)} · {formatCurrency(totalVendorDueCents / 100, currency)}</td>
                  <td></td>
                </tr>
              </tbody>
            </table>
          </div>
        )}
      </div>
    </>
  );
}
